-module(stdlib_demo).
-export([main/0]).

main() ->
    People = [{bob, 32, "Oslo"}, {ada, 36, "London"}, {cy, 32, "Turku"}],
    io:format("~p~n", [lists:keyfind(ada, 1, People)]),
    io:format("~p~n", [lists:keysort(2, People)]),
    io:format("~p~n", [lists:keystore(cy, 1, People, {cy, 33, "Turku"})]),
    io:format("~p ~p~n", [lists:keymember(dan, 1, People), lists:keytake(bob, 1, People)]),
    io:format("~p~n", [lists:sort(fun(A, B) -> A >= B end, [3, 1, 2])]),
    io:format("~p ~p~n", [lists:usort([3, 1, 2, 3, 1]), lists:uniq([3, 1, 2, 3, 1])]),
    io:format("~p ~p~n", [lists:split(2, [a, b, c, d]),
                          lists:partition(fun(X) -> X > 2 end, [1, 2, 3, 4])]),
    io:format("~p ~p ~p~n", [lists:sublist([a, b, c, d], 2, 2), lists:nthtail(3, [a, b, c, d]),
                             lists:droplast([1, 2, 3])]),
    io:format("~p ~p~n", [lists:takewhile(fun(X) -> X < 3 end, [1, 2, 3, 1]),
                          lists:dropwhile(fun(X) -> X < 3 end, [1, 2, 3, 1])]),
    io:format("~p~n", [lists:filtermap(fun(X) when X > 1 -> {true, X * 10}; (_) -> false end,
                                       [1, 2, 3])]),
    io:format("~p ~p~n", [lists:flatmap(fun(X) -> [X, X] end, [a, b]),
                          lists:append([[1], [2, 3], []])]),
    io:format("~p~n", [lists:mapfoldl(fun(X, Sum) -> {X * 2, Sum + X} end, 0, [1, 2, 3])]),
    io:format("~p ~p~n", [lists:enumerate([a, b]), lists:unzip([{a, 1}, {b, 2}])]),
    io:format("~p ~p~n", [lists:zipwith(fun(A, B) -> A * B end, [1, 2], [3, 4]),
                          lists:seq(1, 10, 3)]),
    io:format("~s ~p~n", [lists:concat([file, ".", 3]), lists:join(", ", ["a", "b"])]),
    io:format("~p ~p~n", [lists:prefix([1, 2], [1, 2, 3]), lists:suffix([3], [1, 2, 3])]),
    io:format("~p ~p~n", [lists:search(fun(X) -> X > 1 end, [1, 2, 3]),
                          lists:delete(b, [a, b, c, b])]),
    io:format("~p ~p~n", [string:trim(<<"  hello  ">>), string:trim("xxhixx", both, "x")]),
    io:format("~p ~p~n", [string:split(<<"a=b=c">>, "=", all), string:split("a=b=c", "=", trailing)]),
    io:format("~p ~p~n", [string:lexemes("  one two,three ", " ,"), string:to_upper(<<"hyvää"/utf8>>)]),
    io:format("~s ~p ~p~n", [string:replace("a-b-c", "-", "+", all), string:length(<<"päivä"/utf8>>),
                             string:reverse("abc")]),
    io:format("~p ~p~n", [string:find("hello world", "o w"), string:prefix(<<"foobar">>, "foo")]),
    io:format("~p [~s] ~p~n", [string:slice("hello", 1, 3), string:pad("ab", 5, leading),
                               string:chomp("line\r\n")]),
    io:format("~p ~p~n", [string:to_integer("42 apples"), string:to_integer("none")]),
    Opts = [{name, "alku"}, verbose, {level, 3}],
    io:format("~p ~p ~p~n", [proplists:get_value(name, Opts), proplists:get_value(verbose, Opts),
                             proplists:get_value(missing, Opts, default)]),
    io:format("~p ~p~n", [lists:sort(proplists:get_keys(Opts)), proplists:to_map(Opts)]),
    io:format("~s~n", [io_lib:format("~5.1f|~-4s|~p", [3.14159, "ab", {x}])]),
    io:format("~p ~p~n", [float_to_binary(2.5, [short]), binary_to_float(<<"1.5">>)]),
    io:format("~p ~p~n", [maps:take(a, #{a => 1, b => 2}), maps:from_keys([x, y], 0)]),
    {Time, Result} = timer:tc(fun() -> lists:sum(lists:seq(1, 1000)) end),
    io:format("~p ~p~n", [is_integer(Time) andalso Time >= 0, Result]),
    R = rand:uniform(6),
    io:format("~p ~p~n", [R >= 1 andalso R =< 6, is_float(rand:uniform())]),
    io:format("~p ~p~n", [is_list(os:getenv("PATH")), os:getenv("ALKU_SURELY_UNSET_VARIABLE")]),
    io:format("~p~n", [erlang:make_tuple(3, x)]).
