%% @doc Translates Erlang abstract forms (as produced by erl_parse) into C.
%%
%% How it works:
%% - Every Alku function becomes a C function of type AlkuCode (see
%%   alku_runtime.h). Each fun is lifted out into a C function of its own.
%% - Expressions compile to {Code, Ref, State}: Code is a list of C
%%   statements, Ref a side-effect-free C expression holding the value.
%% - Clauses (of functions, funs, case and if) become C blocks; a failing
%%   pattern or guard jumps to the label in front of the next clause.
%% - The last expression of a body is compiled with a continuation that
%%   says where its value goes: `tail` (return it from the C function) or
%%   {assign, Var, Label, Exports} (store it and jump to Label, used for a
%%   case, if or try whose value is needed; Exports are the variables bound
%%   in every clause, which stay usable after it, as in Erlang).
%% - Exceptions use setjmp/longjmp: try pushes a handler and raising jumps
%%   to the innermost one (see AlkuHandler in alku_runtime.h).
%%
%% Tail calls: in `tail` position, a call to the function being compiled
%% becomes a jump back to its start, and any other call to an Alku
%% function or fun returns a pending tail call to the caller's
%% alku_settle loop instead of calling it. Either way the C stack does
%% not grow, so loops written as recursion run in constant stack space.
-module(alku_codegen).

-export([program/1]).

-record(st, {
    n = 0 :: non_neg_integer(),                     % counter for fresh C names
    vars = #{} :: #{atom() => string()},            % Erlang variable => C variable
    funs :: #{{module(), atom(), arity()} => true}, % every function in the program
    module :: module(),
    cname :: string(),                % the C function being compiled
    arity :: arity(),                 % ... and its arity
    self_ref = none :: none | string(), % C variable holding a named fun itself
    display :: string(),              % "name/arity" of the enclosing function
    fun_count = 0 :: non_neg_integer(), % funs created so far in that function
    lifted = [] :: [{iodata(), iodata()}] % {prototype, definition} of lifted funs
}).

-spec program([{module(), [erl_parse:abstract_form()]}]) ->
    {ok, iodata()} | {error, {module(), non_neg_integer(), iodata()}}.
program([{Main, _} | _] = Modules) ->
    Funs = maps:from_list([{{M, Name, Arity}, true}
                           || {M, Forms} <- Modules,
                              {function, _, Name, Arity, _} <- Forms]),
    try
        MainArity = case Funs of
                        #{{Main, main, 1} := _} -> 1;
                        #{{Main, main, 0} := _} -> 0;
                        _ -> throw({alku_error, Main, 1,
                                    "a program needs a main/0 or main/1 function"})
                    end,
        Compiled = lists:append([compile_function(M, F, Funs)
                                 || {M, Forms} <- Modules,
                                    {function, _, _, _, _} = F <- Forms]),
        {Prototypes, Definitions} = lists:unzip(Compiled),
        Code = ["/* Generated by the Alku compiler from module ",
                atom_to_list(Main), ". */\n",
                "#include \"alku_runtime.h\"\n\n",
                Prototypes, "\n",
                Definitions,
                "int main(int argc, char **argv) {\n",
                "return alku_start(", alku_c:function_name(Main, main, MainArity), ", ",
                integer_to_list(MainArity), ", argc, argv);\n",
                "}\n"],
        {ok, alku_c:indent(Code)}
    catch
        throw:{alku_error, Module, Line, Message} -> {error, {Module, Line, Message}}
    end.

%% ---------- Functions ----------

compile_function(Module, Function, Funs) ->
    try
        function(Module, Function, Funs)
    catch
        throw:{alku_error, Line, Message} -> throw({alku_error, Module, Line, Message})
    end.

%% Returns {Prototype, Definition} for the function and the funs inside it.
function(Module, {function, _, Name, Arity, Clauses}, Funs) ->
    St0 = #st{funs = Funs, module = Module,
              cname = alku_c:function_name(Module, Name, Arity), arity = Arity,
              display = atom_to_list(Name) ++ "/" ++ integer_to_list(Arity)},
    {Prototype, Definition, St} = c_function(atom_to_list(Name), [], Clauses, St0),
    [{Prototype, Definition} | St#st.lifted].

%% The C function St#st.cname. Its arguments are copied into a1..aN first,
%% because the args array may be reused by the next tail call. Prologue
%% runs once; a self tail call jumps back to tail_entry.
c_function(ErrorName, Prologue, Clauses, #st{cname = CName, arity = Arity} = St0) ->
    Params = params(Arity),
    Entry = [["Value ", P, " = args[", integer_to_list(I - 1), "];\n"]
             || {I, P} <- lists:zip(lists:seq(1, Arity), Params)],
    NoMatch = ["alku_error_function_clause(", string_literal(ErrorName), ", ",
               integer_to_list(Arity), ", ", value_array(Params), ");\n"],
    {Body, St1} = clauses(Clauses, Params, tail, NoMatch, St0),
    Header = ["static Value ", CName, "(const Value *args, AlkuFun *self)"],
    Definition = [Header, " {\n",
                  Entry,
                  "(void)args;\n",
                  "(void)self;\n",
                  Prologue,
                  "tail_entry: ;\n",
                  Body,
                  "}\n\n"],
    {[Header, ";\n"], Definition, St1}.

params(Arity) ->
    ["a" ++ integer_to_list(I) || I <- lists:seq(1, Arity)].

%% ---------- Clauses, patterns and guards ----------

%% Compiles clauses matched against Subjects (C refs). Each clause body
%% ends with continuation K; NoMatch runs when no clause matches.
%% Variables bound in a clause are only visible inside it.
clauses([], _Subjects, _K, NoMatch, St) ->
    {NoMatch, St};
clauses([{clause, _, Patterns, Guards, Body} | Rest], Subjects, K, NoMatch, St0) ->
    {Next, St1} = fresh("next", St0),
    Fail = ["goto ", Next, ";"],
    {PatternCode, St2} = patterns(Patterns, Subjects, Fail, St1),
    {GuardCode, St3} = guard(Guards, Fail, St2),
    {BodyCode, St4} = body(Body, K, St3),
    {RestCode, St5} = clauses(Rest, Subjects, K, NoMatch,
                              St4#st{vars = St0#st.vars}),
    Code = ["{\n", PatternCode, GuardCode, BodyCode, "}\n",
            Next, ": ;\n",
            RestCode],
    {Code, St5}.

patterns([], [], _Fail, St) ->
    {[], St};
patterns([P | Ps], [S | Ss], Fail, St0) ->
    {Code, St1} = pattern(P, S, Fail, St0),
    {Rest, St2} = patterns(Ps, Ss, Fail, St1),
    {[Code, Rest], St2}.

%% Matches pattern P against the C ref Subject, running Fail on mismatch.
pattern({var, _, '_'}, _Subject, _Fail, St) ->
    {[], St};
pattern({var, _, Name}, Subject, Fail, St0) ->
    case St0#st.vars of
        #{Name := CVar} ->  % already bound: the values must be equal
            {check(["alku_exact_eq(", CVar, ", ", Subject, ")"], Fail), St0};
        _ ->
            {CVar, St1} = fresh_var(Name, St0),
            {["Value ", CVar, " = ", Subject, ";\n"], St1}
    end;
pattern({tuple, _, Elements}, Subject, Fail, St0) ->
    Size = integer_to_list(length(Elements)),
    Subjects = [["alku_tuple_element(", Subject, ", ", integer_to_list(I), ")"]
                || I <- lists:seq(0, length(Elements) - 1)],
    {Code, St1} = patterns(Elements, Subjects, Fail, St0),
    {[check(["alku_is_tuple_of(", Subject, ", ", Size, ")"], Fail), Code], St1};
pattern({cons, _, Head, Tail}, Subject, Fail, St0) ->
    Subjects = [["alku_head(", Subject, ")"], ["alku_tail(", Subject, ")"]],
    {Code, St1} = patterns([Head, Tail], Subjects, Fail, St0),
    {[check(["alku_is_cons(", Subject, ")"], Fail), Code], St1};
pattern({string, Anno, Chars}, Subject, Fail, St) ->
    pattern(string_to_list_pattern(Chars, Anno), Subject, Fail, St);
pattern({match, _, P1, P2}, Subject, Fail, St0) ->
    {Code1, St1} = pattern(P1, Subject, Fail, St0),
    {Code2, St2} = pattern(P2, Subject, Fail, St1),
    {[Code1, Code2], St2};
pattern(P, Subject, Fail, St) ->
    case literal(P) of
        {ok, Literal} ->
            {check(["alku_exact_eq(", Subject, ", ", Literal, ")"], Fail), St};
        error ->
            unsupported(P)
    end.

%% "abc" in a pattern means [$a, $b, $c].
string_to_list_pattern([], Anno) ->
    {nil, Anno};
string_to_list_pattern([C | Cs], Anno) ->
    {cons, Anno, {char, Anno, C}, string_to_list_pattern(Cs, Anno)}.

%% Guards are a list of alternatives (separated by ;), each a list of
%% tests (separated by ,) that must all be true.
guard([], _Fail, St) ->
    {[], St};
guard([Tests], Fail, St) ->
    guard_alternative(Tests, Fail, St);
guard(Alternatives, Fail, St0) ->
    {Ok, St1} = fresh("guard_ok", St0),
    guard_alternatives(Alternatives, Ok, Fail, St1).

guard_alternatives([Tests], Ok, Fail, St0) ->
    {Code, St1} = guard_alternative(Tests, Fail, St0),
    {["{\n", Code, "}\n", Ok, ": ;\n"], St1};
guard_alternatives([Tests | Rest], Ok, Fail, St0) ->
    {Next, St1} = fresh("guard_alt", St0),
    {Code, St2} = guard_alternative(Tests, ["goto ", Next, ";"], St1),
    {RestCode, St3} = guard_alternatives(Rest, Ok, Fail, St2),
    {["{\n", Code, "goto ", Ok, ";\n}\n", Next, ": ;\n", RestCode], St3}.

%% In Erlang an exception in a guard just makes it false. Guards that
%% cannot raise (comparisons and type tests on variables, the usual case)
%% are compiled as they are; others run under an exception handler.
guard_alternative(Tests, Fail, St0) ->
    case lists:all(fun safe_guard/1, Tests) of
        true ->
            guard_tests(Tests, Fail, St0);
        false ->
            {H, St1} = fresh("guard_handler", St0),
            {Code, St2} = guard_tests(Tests, ["{ alku_end_try(&", H, "); ", Fail, " }"], St1),
            {["{\n",
              "AlkuHandler ", H, ";\n",
              "alku_try(&", H, ");\n",
              "if (setjmp(", H, ".env) != 0) ", Fail, "\n",
              Code,
              "alku_end_try(&", H, ");\n",
              "}\n"], St2}
    end.

safe_guard({var, _, _}) -> true;
safe_guard(E) -> literal(E) =/= error orelse boolean_safe(E).

%% Boolean-valued guard expressions that can never raise.
boolean_safe({atom, _, B}) -> B =:= true orelse B =:= false;
boolean_safe({op, _, Op, A, B}) when Op =:= 'andalso'; Op =:= 'orelse';
                                     Op =:= 'and'; Op =:= 'or'; Op =:= 'xor' ->
    boolean_safe(A) andalso boolean_safe(B);
boolean_safe({op, _, 'not', A}) ->
    boolean_safe(A);
boolean_safe({op, _, Op, A, B}) ->
    lists:member(Op, ['==', '/=', '=:=', '=/=', '<', '>', '=<', '>=']) andalso
        total(A) andalso total(B);
boolean_safe({call, _, {atom, _, F}, [A]}) ->
    type_test(F) andalso total(A);
boolean_safe({call, _, {remote, _, {atom, _, erlang}, {atom, _, F}}, [A]}) ->
    type_test(F) andalso total(A);
boolean_safe(_) ->
    false.

type_test(F) ->
    lists:member(F, [is_integer, is_atom, is_boolean, is_list, is_tuple, is_function]).

%% Expressions whose evaluation cannot raise.
total({var, _, _}) -> true;
total({tuple, _, Es}) -> lists:all(fun total/1, Es);
total({cons, _, H, T}) -> total(H) andalso total(T);
total({string, _, _}) -> true;
total(E) -> literal(E) =/= error.

guard_tests([], _Fail, St) ->
    {[], St};
guard_tests([Test | Tests], Fail, St0) ->
    {Code, Ref, St1} = expr(Test, St0),
    {Rest, St2} = guard_tests(Tests, Fail, St1),
    {[Code, check(["alku_is_true(", Ref, ")"], Fail), Rest], St2}.

check(Condition, Fail) ->
    ["if (!", Condition, ") ", Fail, "\n"].

%% ---------- Bodies and continuations ----------

body([E], K, St) ->
    expr_k(E, K, St);
body([E | Es], K, St0) ->
    {Code, _Ref, St1} = expr(E, St0),
    {Rest, St2} = body(Es, K, St1),
    {[Code, Rest], St2}.

%% Compiles E so that its value goes to continuation K.
expr_k({'case', _, E, Clauses}, K, St0) ->
    {Code, Ref, St1} = expr(E, St0),
    {Branches, St2} = clauses(Clauses, [Ref], K,
                              ["alku_error_case_clause(", Ref, ");\n"], St1),
    {[Code, Branches], St2};
expr_k({'if', _, Clauses}, K, St) ->
    clauses(Clauses, [], K, "alku_error_if_clause();\n", St);
expr_k({block, _, Body}, K, St) ->
    body(Body, K, St);
expr_k({op, _, Op, A, B}, K, St0) when Op =:= 'andalso'; Op =:= 'orelse' ->
    %% B is in the same position as the whole expression, so it can be a
    %% tail call: all(P, [X | Xs]) -> P(X) andalso all(P, Xs).
    {CodeA, RefA, St1} = expr(A, St0),
    {CodeT, T, St2} = temp(RefA, St1),
    Test = case Op of
               'andalso' -> ["alku_is_true(", T, ")"];
               'orelse' -> ["!alku_is_true(", T, ")"]
           end,
    {CodeB, St3} = expr_k(B, K, St2),
    Code = [CodeA, CodeT,
            "alku_check_boolean(", T, ");\n",
            "if (", Test, ") {\n", CodeB, "}\n",
            continue(K, T, St2)],
    {Code, St3#st{vars = St2#st.vars}};
expr_k({call, Anno, Callee, Args}, tail, St0) ->
    {ArgCode, Refs, St1} = exprs(Args, St0),
    {CalleeCode, Target, St2} = callee(Callee, length(Args), Anno, St1),
    {[ArgCode, CalleeCode, tail_call(Target, Refs, St2)], St2};
expr_k({'try', _, Body, OfClauses, CatchClauses, []}, K, St0) ->
    %% try Body of OfClauses catch CatchClauses end
    {H, St1} = fresh("handler", St0),
    {BodyCode, BodyRef, St2} = sequence(Body, St1),
    {Normal, St3} =
        case OfClauses of
            [] -> {continue(K, BodyRef, St2), St2};
            _ -> clauses(OfClauses, [BodyRef], K,
                         ["alku_error_try_clause(", BodyRef, ");\n"], St2)
        end,
    {Caught, St4} = catch_clauses(CatchClauses, K, St3#st{vars = St1#st.vars}),
    Code = ["AlkuHandler ", H, ";\n",
            "alku_try(&", H, ");\n",
            "if (setjmp(", H, ".env) == 0) {\n",
            BodyCode,
            "alku_end_try(&", H, ");\n",
            Normal, % ends with return, goto or a raise
            "}\n",
            Caught],
    {Code, St4#st{vars = St1#st.vars}};
expr_k({'try', Anno, Body, OfClauses, CatchClauses, After}, K, St0) ->
    %% ... after After end: run After whether or not an exception happened
    Inner = case {OfClauses, CatchClauses} of
                {[], []} -> {block, Anno, Body};
                _ -> {'try', Anno, Body, OfClauses, CatchClauses, []}
            end,
    {H, St1} = fresh("handler", St0),
    {R, St2} = fresh("r", St1),
    {InnerCode, InnerRef, St3} = expr(Inner, St2),
    {AfterOk, _, St4} = sequence(After, St3#st{vars = St2#st.vars}),
    {AfterError, _, St5} = sequence(After, St4#st{vars = St2#st.vars}),
    Code = ["AlkuHandler ", H, ";\n",
            "Value ", R, ";\n",
            "alku_try(&", H, ");\n",
            "if (setjmp(", H, ".env) == 0) {\n",
            InnerCode,
            R, " = ", InnerRef, ";\n",
            "alku_end_try(&", H, ");\n",
            "} else {\n",
            AfterError,
            "alku_raise(alku_caught_class(), alku_caught_reason());\n",
            "}\n",
            AfterOk],
    St6 = St5#st{vars = St2#st.vars},
    {[Code, continue(K, R, St6)], St6};
expr_k(E, K, St0) ->
    {Code, Ref, St1} = expr(E, St0),
    {[Code, continue(K, Ref, St1)], St1}.

%% The catch part of a try, run after an exception has jumped back here.
%% Each clause looks like Class:Reason:Stacktrace (the stacktrace is []).
catch_clauses(Clauses0, K, St0) ->
    {Class, St1} = fresh("class", St0),
    {Reason, St2} = fresh("reason", St1),
    Clauses = [{clause, A, [C, R], G, [{match, A, S, {nil, A}} | B]}
               || {clause, A, [{tuple, _, [C, R, S]}], G, B} <- Clauses0],
    Reraise = ["alku_raise(", Class, ", ", Reason, ");\n"],
    {Code, St3} = clauses(Clauses, [Class, Reason], K, Reraise, St2),
    {["{\n",
      "Value ", Class, " = alku_caught_class();\n",
      "Value ", Reason, " = alku_caught_reason();\n",
      Code,
      "}\n"], St3}.

continue(tail, Ref, _St) ->
    ["return ", Ref, ";\n"];
continue({assign, Var, Label, Exports}, Ref, St) ->
    %% copy exported variables bound on this path into their shared C variables
    [[[CVar, " = ", Bound, ";\n"] || {Name, CVar} <- Exports,
                                     {ok, Bound} <- [maps:find(Name, St#st.vars)],
                                     Bound =/= CVar],
     Var, " = ", Ref, ";\ngoto ", Label, ";\n"].

%% case, if, try, andalso and orelse in value position: the branches store
%% the result in one C variable and jump to the end.
via_continuation(E, St0) ->
    {Result, St1} = fresh("r", St0),
    {End, St2} = fresh("end", St1),
    {Decls, Exports, St3} = exports(E, St2),
    {Code, St4} = expr_k(E, {assign, Result, End, Exports}, St3),
    Vars = maps:merge(St2#st.vars, maps:from_list(Exports)),
    {["Value ", Result, ";\n", Decls, Code, End, ": ;\n"], Result, St4#st{vars = Vars}}.

%% Variables that every clause of a case or if binds can be used after it.
%% erl_lint rejects uses of variables bound in only some clauses, so
%% variables new in every clause are enough to look at.
exports(E, St0) ->
    Clauses = case E of
                  {'case', _, _, Cs} -> Cs;
                  {'if', _, Cs} -> Cs;
                  _ -> []
              end,
    New = [[V || V <- lists:usort(vars_outside_funs(C)), not maps:is_key(V, St0#st.vars)]
           || C <- Clauses],
    Names = case New of
                [] -> [];
                [First | Rest] ->
                    lists:foldl(fun(Vs, Acc) -> [V || V <- Acc, lists:member(V, Vs)] end,
                                First, Rest)
            end,
    lists:foldr(fun(Name, {Decls, Exports, St}) ->
                        {N, St1} = next(St),
                        CVar = alku_c:var_name(Name, N),
                        {[["Value ", CVar, ";\n"] | Decls], [{Name, CVar} | Exports], St1}
                end, {[], [], St0}, Names).

%% Variables in an expression, except those local to funs and list
%% comprehensions inside it.
vars_outside_funs({'fun', _, _}) -> [];
vars_outside_funs({named_fun, _, _, _}) -> [];
vars_outside_funs({lc, _, _, _}) -> [];
vars_outside_funs(T) when element(1, T) =:= var -> vars_in(T);
vars_outside_funs(T) when is_tuple(T) -> vars_outside_funs(tuple_to_list(T));
vars_outside_funs(L) when is_list(L) -> lists:flatmap(fun vars_outside_funs/1, L);
vars_outside_funs(_) -> [].

%% ---------- Calls ----------

%% What a call goes to: {alku, CName} (a function in the program),
%% {bif, CFun} (a runtime function) or {apply, FunRef} (a fun value).
callee({atom, _, Name}, Arity, Anno, #st{module = Module} = St) ->
    {[], resolve(Module, Name, Arity, erlang, Anno, St), St};
callee({remote, _, {atom, _, Module}, {atom, _, Name}}, Arity, Anno, St) ->
    {[], resolve(Module, Name, Arity, Module, Anno, St), St};
callee(Expr, _Arity, _Anno, St0) ->
    {Code, Ref, St1} = expr(Expr, St0),
    {Code, {apply, Ref}, St1}.

%% A function of the program if there is one, otherwise a built-in.
resolve(Module, Name, Arity, BifModule, Anno, St) ->
    case maps:is_key({Module, Name, Arity}, St#st.funs) of
        true -> {alku, alku_c:function_name(Module, Name, Arity)};
        false -> {bif, builtin(BifModule, Name, Arity, Anno)}
    end.

%% A normal call: run any pending tail calls to get the real value.
call({alku, CName}, Refs) ->
    ["alku_settle(", CName, "(", value_array(Refs), ", NULL))"];
call({bif, CFun}, Refs) ->
    [CFun, "(", lists:join(", ", Refs), ")"];
call({apply, Fun}, Refs) ->
    ["alku_settle(alku_apply(", Fun, ", ", integer_to_list(length(Refs)), ", ",
     value_array(Refs), "))"].

tail_call({alku, CName}, Refs, #st{cname = CName, arity = Arity})
  when length(Refs) =:= Arity ->
    self_tail_call(Refs);
tail_call({apply, Ref}, Refs, #st{self_ref = Ref, arity = Arity})
  when length(Refs) =:= Arity ->
    self_tail_call(Refs);
tail_call({alku, CName}, Refs, _St) ->
    ["return alku_tail_call(", CName, ", NULL, ", integer_to_list(length(Refs)), ", ",
     value_array(Refs), ");\n"];
tail_call({apply, Fun}, Refs, _St) ->
    ["return alku_tail_apply(", Fun, ", ", integer_to_list(length(Refs)), ", ",
     value_array(Refs), ");\n"];
tail_call({bif, _} = Target, Refs, _St) ->
    ["return ", call(Target, Refs), ";\n"].

%% Calling ourselves in tail position: new arguments, then jump back to the
%% start. The new values are computed before any argument is overwritten.
self_tail_call(Refs) ->
    Numbered = lists:zip(lists:seq(1, length(Refs)), Refs),
    ["{\n",
     [["Value next_arg", integer_to_list(I), " = ", Ref, ";\n"] || {I, Ref} <- Numbered],
     [["a", integer_to_list(I), " = next_arg", integer_to_list(I), ";\n"]
      || {I, _} <- Numbered],
     "goto tail_entry;\n",
     "}\n"].

%% ---------- Expressions ----------

expr(E, St) ->
    case literal(E) of
        {ok, Literal} -> {[], Literal, St};
        error -> compound(E, St)
    end.

compound({var, Anno, Name}, St) ->
    case St#st.vars of
        #{Name := CVar} ->
            {[], CVar, St};
        _ ->
            fail(Anno, io_lib:format("variable '~s' is bound inside a case or if "
                                     "and cannot be used after it yet", [Name]))
    end;
compound({match, _, Pattern, E}, St0) ->
    {Code, Ref, St1} = expr(E, St0),
    {Match, St2} = pattern(Pattern, Ref, ["alku_error_badmatch(", Ref, ");"], St1),
    {[Code, Match], Ref, St2};
compound({op, _, Op, _, _} = E, St) when Op =:= 'andalso'; Op =:= 'orelse' ->
    via_continuation(E, St);
compound({op, Anno, Op, A, B}, St0) ->
    Fun = binary_op(Op, Anno),
    {CodeA, RefA, St1} = expr(A, St0),
    {CodeB, RefB, St2} = expr(B, St1),
    {CodeT, T, St3} = temp([Fun, "(", RefA, ", ", RefB, ")"], St2),
    {[CodeA, CodeB, CodeT], T, St3};
compound({op, Anno, Op, A}, St0) ->
    Fun = unary_op(Op, Anno),
    {CodeA, RefA, St1} = expr(A, St0),
    {CodeT, T, St2} = temp([Fun, "(", RefA, ")"], St1),
    {[CodeA, CodeT], T, St2};
compound({call, Anno, Callee, Args}, St0) ->
    {ArgCode, Refs, St1} = exprs(Args, St0),
    {CalleeCode, Target, St2} = callee(Callee, length(Args), Anno, St1),
    {CodeT, T, St3} = temp(call(Target, Refs), St2),
    {[ArgCode, CalleeCode, CodeT], T, St3};
compound({'case', _, _, _} = E, St) ->
    via_continuation(E, St);
compound({'if', _, _} = E, St) ->
    via_continuation(E, St);
compound({'try', _, _, _, _, _} = E, St) ->
    via_continuation(E, St);
compound({'catch', _, E}, St0) ->
    %% catch Expr: the value, or what the exception turns into
    {H, St1} = fresh("catch", St0),
    {R, St2} = fresh("r", St1),
    {Code, Ref, St3} = expr(E, St2),
    {["Value ", R, ";\n",
      "AlkuHandler ", H, ";\n",
      "alku_try(&", H, ");\n",
      "if (setjmp(", H, ".env) == 0) {\n",
      Code,
      R, " = ", Ref, ";\n",
      "alku_end_try(&", H, ");\n",
      "} else {\n",
      R, " = alku_catch_value(alku_caught_class(), alku_caught_reason());\n",
      "}\n"], R, St3#st{vars = St2#st.vars}};
compound({lc, Anno, Template, Qualifiers}, St0) ->
    {Loop, St1} = list_comprehension(Template, Qualifiers, {nil, Anno}, St0),
    expr({call, Anno, {remote, Anno, {atom, Anno, lists}, {atom, Anno, reverse}}, [Loop]}, St1);
compound({block, _, Body}, St) ->
    sequence(Body, St);
compound({tuple, _, Elements}, St0) ->
    {Codes, Refs, St1} = exprs(Elements, St0),
    {CodeT, T, St2} = temp(["alku_make_tuple(", integer_to_list(length(Refs)), ", ",
                            value_array(Refs), ")"], St1),
    {[Codes, CodeT], T, St2};
compound({cons, _, Head, Tail}, St0) ->
    {Codes, [RefH, RefT], St1} = exprs([Head, Tail], St0),
    {CodeT, T, St2} = temp(["alku_cons(", RefH, ", ", RefT, ")"], St1),
    {[Codes, CodeT], T, St2};
compound({string, _, Chars}, St) ->
    Bytes = unicode:characters_to_binary(Chars),
    temp(["alku_string(", alku_c:string_literal(Bytes), ", ",
          integer_to_list(byte_size(Bytes)), ")"], St);
compound({'fun', Anno, {function, Name, Arity}}, #st{module = Module} = St) ->
    case maps:is_key({Module, Name, Arity}, St#st.funs) of
        true ->
            Display = io_lib:format("~s.~s/~b", [Module, Name, Arity]),
            make_fun(alku_c:function_name(Module, Name, Arity), Arity, Display, [], St);
        false ->
            external_fun(erlang, Name, Arity, Anno, St)
    end;
compound({'fun', Anno, {function, {atom, _, Module}, {atom, _, Name}, {integer, _, Arity}}}, St) ->
    external_fun(Module, Name, Arity, Anno, St);
compound({'fun', _, {clauses, Clauses}}, St) ->
    lambda(none, Clauses, St);
compound({named_fun, _, Name, Clauses}, St) ->
    lambda(Name, Clauses, St);
compound(E, _St) ->
    unsupported(E).

%% A body whose value is needed; variables it binds stay visible.
sequence([E], St) ->
    expr(E, St);
sequence([E | Es], St0) ->
    {Code, _Ref, St1} = expr(E, St0),
    {Rest, Ref, St2} = sequence(Es, St1),
    {[Code, Rest], Ref, St2}.

exprs([], St) ->
    {[], [], St};
exprs([E | Es], St0) ->
    {Code, Ref, St1} = expr(E, St0),
    {Codes, Refs, St2} = exprs(Es, St1),
    {[Code | Codes], [Ref | Refs], St2}.

%% A C array of values, for passing several values to the runtime.
value_array([]) -> "NULL";
value_array(Refs) -> ["(Value[]){", lists:join(", ", Refs), "}"].

%% ---------- List comprehensions ----------

%% [T || Qualifiers] is rewritten into named funs that loop over each
%% generator, collecting results in reverse into Acc; the caller reverses
%% the result. The loops are tail-recursive, so they run in constant stack.
list_comprehension(Template, [], Acc, St) ->
    {{cons, element(2, Acc), Template, Acc}, St};
list_comprehension(Template, [{generate, A, Pattern, List} | Qs], Acc, St0) ->
    {LoopName, St1} = fresh_name("Lc@Loop", St0),
    {TailName, St2} = fresh_name("Lc@Tail", St1),
    {AccName, St3} = fresh_name("Lc@Acc", St2),
    Loop = {var, A, LoopName},
    Tail = {var, A, TailName},
    LoopAcc = {var, A, AccName},
    {Inner, St4} = list_comprehension(Template, Qs, LoopAcc, St3),
    Fun = {named_fun, A, LoopName,
           [{clause, A, [{cons, A, Pattern, Tail}, LoopAcc], [],
             [{call, A, Loop, [Tail, Inner]}]},
            {clause, A, [{cons, A, {var, A, '_'}, Tail}, LoopAcc], [],
             [{call, A, Loop, [Tail, LoopAcc]}]},
            {clause, A, [{nil, A}, LoopAcc], [], [LoopAcc]}]},
    {{call, A, Fun, [List, Acc]}, St4};
list_comprehension(Template, [Filter | Qs], Acc, St0) ->
    A = element(2, Filter),
    {Inner, St1} = list_comprehension(Template, Qs, Acc, St0),
    {{'case', A, Filter, [{clause, A, [{atom, A, true}], [], [Inner]},
                          {clause, A, [{atom, A, false}], [], [Acc]}]}, St1}.

%% A variable name that cannot clash with the program's own variables.
fresh_name(Prefix, St0) ->
    {N, St1} = next(St0),
    {list_to_atom(Prefix ++ integer_to_list(N)), St1}.

%% ---------- Funs ----------

%% fun M:F/A. Built-ins have a different C signature, so they get a small
%% adapter function.
external_fun(Module, Name, Arity, Anno, St0) ->
    Display = io_lib:format("fun ~s:~s/~b", [Module, Name, Arity]),
    case resolve(Module, Name, Arity, Module, Anno, St0) of
        {alku, CName} ->
            make_fun(CName, Arity, Display, [], St0);
        {bif, CFun} ->
            {Adapter, St1} = fresh_fun_name(St0),
            Args = ["args[" ++ integer_to_list(I) ++ "]" || I <- lists:seq(0, Arity - 1)],
            Header = ["static Value ", Adapter, "(const Value *args, AlkuFun *self)"],
            Definition = [Header, " {\n",
                          "(void)args;\n",
                          "(void)self;\n",
                          "return ", CFun, "(", lists:join(", ", Args), ");\n",
                          "}\n\n"],
            St2 = St1#st{lifted = [{[Header, ";\n"], Definition} | St1#st.lifted]},
            make_fun(Adapter, Arity, Display, [], St2)
    end.

%% fun (...) -> ... end and fun Name(...) -> ... end. The body becomes its
%% own C function; variables it uses from the enclosing scope are captured
%% in the fun object and read back from self->env.
lambda(SelfName, [{clause, _, Patterns, _, _} | _] = Clauses0, St0) ->
    Arity = length(Patterns),
    {CName, St1} = fresh_fun_name(St0),
    Index = St1#st.fun_count,
    Display = "-" ++ St1#st.display ++ "-fun-" ++ integer_to_list(Index) ++ "-",
    Outer = St1#st.vars,
    Clauses = [rename_shadowed(C, Outer, SelfName) || C <- Clauses0],
    Free = [V || V <- lists:usort(vars_in(Clauses)), V =/= SelfName,
                 maps:is_key(V, Outer)],
    Inner0 = St1#st{n = 0, vars = #{}, cname = CName, arity = Arity,
                    self_ref = none, fun_count = Index + 1, lifted = []},
    {Captures, Inner1} = capture(Free, 0, Inner0),
    {SelfCode, Inner2} =
        case SelfName of
            none ->
                {[], Inner1};
            _ ->
                {"Value self_value = alku_fun_value(self);\n",
                 Inner1#st{self_ref = "self_value",
                           vars = maps:put(SelfName, "self_value", Inner1#st.vars)}}
        end,
    {Prototype, Definition, Inner3} = c_function(Display, [Captures, SelfCode], Clauses, Inner2),
    St2 = St1#st{fun_count = Inner3#st.fun_count,
                 lifted = [{Prototype, Definition} | Inner3#st.lifted ++ St1#st.lifted]},
    make_fun(CName, Arity, [atom_to_list(St1#st.module), ".", Display],
             [maps:get(V, Outer) || V <- Free], St2).

capture([], _Index, St) ->
    {[], St};
capture([Name | Names], Index, St0) ->
    {CVar, St1} = fresh_var(Name, St0),
    {Rest, St2} = capture(Names, Index + 1, St1),
    {[["Value ", CVar, " = self->env[", integer_to_list(Index), "];\n"] | Rest], St2}.

make_fun(CName, Arity, Display, FreeRefs, St) ->
    temp(["alku_make_fun(", CName, ", ", integer_to_list(Arity), ", ",
          string_literal(Display), ", ", integer_to_list(length(FreeRefs)), ", ",
          value_array(FreeRefs), ")"], St).

fresh_fun_name(#st{n = N, cname = CName} = St) ->
    {CName ++ "_fun" ++ integer_to_list(N), St#st{n = N + 1}}.

%% Variables in a fun head are always new, even if the enclosing scope has
%% one with the same name (erl_lint warns about this). Renaming them keeps
%% them apart from the captured ones.
rename_shadowed({clause, _, Patterns, _, _} = Clause, Outer, SelfName) ->
    Shadowed = [V || V <- lists:usort(vars_in(Patterns)),
                     maps:is_key(V, Outer) orelse V =:= SelfName],
    lists:foldl(fun(V, C) -> rename(C, V, list_to_atom(atom_to_list(V) ++ "@shadow")) end,
                Clause, Shadowed).

vars_in({var, _, '_'}) -> [];
vars_in({var, _, Name}) -> [Name];
vars_in(T) when is_tuple(T) -> vars_in(tuple_to_list(T));
vars_in(L) when is_list(L) -> lists:flatmap(fun vars_in/1, L);
vars_in(_) -> [].

rename({var, Anno, Old}, Old, New) -> {var, Anno, New};
rename(T, Old, New) when is_tuple(T) -> list_to_tuple(rename(tuple_to_list(T), Old, New));
rename(L, Old, New) when is_list(L) -> [rename(X, Old, New) || X <- L];
rename(X, _Old, _New) -> X.

