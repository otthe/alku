%% ---------- State and errors ----------

next(#st{n = N} = St) ->
    {N, St#st{n = N + 1}}.

fresh(Prefix, St0) ->
    {N, St1} = next(St0),
    {Prefix ++ "_" ++ integer_to_list(N), St1}.

fresh_var(Name, #st{n = N, vars = Vars} = St) ->
    CVar = alku_c:var_name(Name, N),
    {CVar, St#st{n = N + 1, vars = Vars#{Name => CVar}}}.

temp(CExpr, St0) ->
    {T, St1} = fresh("t", St0),
    {["Value ", T, " = ", CExpr, ";\n"], T, St1}.

unsupported(E) ->
    What = case element(1, E) of
               float -> "floats are";
               map -> "maps are";
               map_field_assoc -> "maps are";
               record -> "records are";
               bin -> "binaries are";
               'receive' -> "receive expressions are (Alku has no processes)";
               _ -> "this kind of expression or pattern is"
           end,
    fail(element(2, E), [What, " not supported in Alku yet"]).

%% Anno is an erl_anno() or a plain line number.
fail(Anno, Message) ->
    throw({alku_error, erl_anno:line(Anno), Message}).
