%% @doc Translates Erlang abstract forms (as produced by erl_parse) into C.
%%
%% How it works:
%% - Every expression compiles to {Code, Ref, State}: Code is a list of C
%%   statements, Ref is a side-effect-free C expression (a literal or a
%%   variable) that holds the expression's value once Code has run.
%% - Clauses (of functions, case and if) become C blocks. When a pattern or
%%   guard fails, the block jumps to a label in front of the next clause.
%%
%% Use alku_c:indent/1 on the result if you want readable output; module/1
%% already does this.
-module(alku_codegen).

-export([module/1]).

-record(st, {
    n = 0 :: non_neg_integer(),  % counter for fresh C names
    vars = #{} :: #{atom() => string()},  % Erlang variable => C variable
    funs = #{} :: #{{atom(), arity()} => true},  % functions in this module
    module :: atom()
}).

-spec module([erl_parse:abstract_form()]) ->
    {ok, iodata()} | {error, {pos_integer(), iodata()}}.
module(Forms) ->
    Funs = [F || {function, _, _, _, _} = F <- Forms],
    Defined = maps:from_list([{{Name, Arity}, true}
                              || {function, _, Name, Arity, _} <- Funs]),
    [Module | _] = [M || {attribute, _, module, M} <- Forms],
    St = #st{funs = Defined, module = Module},
    try
        require_main(Defined),
        Code = ["/* Generated by the Alku compiler from module ",
                atom_to_list(Module), ". */\n",
                "#include \"alku_runtime.h\"\n\n",
                [prototype(F) || F <- Funs], "\n",
                [function(F, St) || F <- Funs],
                c_main()],
        {ok, alku_c:indent(Code)}
    catch
        throw:{alku_error, Line, Message} -> {error, {Line, Message}}
    end.

%% ---------- Functions ----------

require_main(#{{main, 0} := _}) -> ok;
require_main(_) -> fail(1, "a program needs a main/0 function").

prototype({function, _, Name, Arity, _}) ->
    Types = case Arity of
                0 -> "void";
                _ -> lists:join(", ", lists:duplicate(Arity, "Value"))
            end,
    ["static Value ", alku_c:function_name(Name, Arity), "(", Types, ");\n"].

function({function, _, Name, Arity, Clauses}, St) ->
    Params = ["a" ++ integer_to_list(I) || I <- lists:seq(1, Arity)],
    Decl = case Params of
               [] -> "void";
               _ -> lists:join(", ", ["Value " ++ P || P <- Params])
           end,
    Args = case Params of
               [] -> "NULL";
               _ -> ["(Value[]){", lists:join(", ", Params), "}"]
           end,
    Done = fun(Ref) -> ["return ", Ref, ";\n"] end,
    NoMatch = ["alku_error_function_clause(", atom_literal_name(Name), ", ",
               integer_to_list(Arity), ", ", Args, ");\n"],
    {Body, _} = clauses(Clauses, Params, Done, NoMatch, St),
    ["static Value ", alku_c:function_name(Name, Arity), "(", Decl, ") {\n",
     Body, "}\n\n"].

c_main() ->
    ["int main(void) {\n",
     "(void)", alku_c:function_name(main, 0), "();\n",
     "return 0;\n",
     "}\n"].

%% ---------- Clauses, patterns and guards ----------

%% Compiles a chain of clauses matched against Subjects (C refs). Done(Ref)
%% is the C code to run with a clause's result; NoMatch runs when no clause
%% matches. Variables bound in a clause are only visible inside it.
clauses([], _Subjects, _Done, NoMatch, St) ->
    {NoMatch, St};
clauses([{clause, _, Patterns, Guards, Body} | Rest], Subjects, Done, NoMatch, St0) ->
    {Next, St1} = fresh("next", St0),
    Fail = ["goto ", Next, ";"],
    {PatternCode, St2} = patterns(Patterns, Subjects, Fail, St1),
    {GuardCode, St3} = guard(Guards, Fail, St2),
    {BodyCode, Ref, St4} = body(Body, St3),
    {RestCode, St5} = clauses(Rest, Subjects, Done, NoMatch,
                              St4#st{vars = St0#st.vars}),
    Code = ["{\n", PatternCode, GuardCode, BodyCode, Done(Ref), "}\n",
            Next, ": ;\n",
            RestCode],
    {Code, St5}.

patterns([], [], _Fail, St) ->
    {[], St};
patterns([P | Ps], [S | Ss], Fail, St0) ->
    {Code, St1} = pattern(P, S, Fail, St0),
    {Rest, St2} = patterns(Ps, Ss, Fail, St1),
    {[Code, Rest], St2}.

%% Matches pattern P against the C ref Subject, running Fail on mismatch.
pattern({var, _, '_'}, _Subject, _Fail, St) ->
    {[], St};
pattern({var, _, Name}, Subject, Fail, St0) ->
    case St0#st.vars of
        #{Name := CVar} ->  % already bound: the values must be equal
            {check(["alku_exact_eq(", CVar, ", ", Subject, ")"], Fail), St0};
        _ ->
            {CVar, St1} = fresh_var(Name, St0),
            {["Value ", CVar, " = ", Subject, ";\n"], St1}
    end;
pattern({match, _, P1, P2}, Subject, Fail, St0) ->
    {Code1, St1} = pattern(P1, Subject, Fail, St0),
    {Code2, St2} = pattern(P2, Subject, Fail, St1),
    {[Code1, Code2], St2};
pattern(P, Subject, Fail, St) ->
    case literal(P) of
        {ok, Literal} ->
            {check(["alku_exact_eq(", Subject, ", ", Literal, ")"], Fail), St};
        error ->
            unsupported(P)
    end.

%% Guards are a list of alternatives (separated by ;), each a list of
%% tests (separated by ,) that must all be true.
guard([], _Fail, St) ->
    {[], St};
guard([Tests], Fail, St) ->
    guard_tests(Tests, Fail, St);
guard(Alternatives, Fail, St0) ->
    {Ok, St1} = fresh("guard_ok", St0),
    guard_alternatives(Alternatives, Ok, Fail, St1).

guard_alternatives([Tests], Ok, Fail, St0) ->
    {Code, St1} = guard_tests(Tests, Fail, St0),
    {["{\n", Code, "}\n", Ok, ": ;\n"], St1};
guard_alternatives([Tests | Rest], Ok, Fail, St0) ->
    {Next, St1} = fresh("guard_alt", St0),
    {Code, St2} = guard_tests(Tests, ["goto ", Next, ";"], St1),
    {RestCode, St3} = guard_alternatives(Rest, Ok, Fail, St2),
    {["{\n", Code, "goto ", Ok, ";\n}\n", Next, ": ;\n", RestCode], St3}.

guard_tests([], _Fail, St) ->
    {[], St};
guard_tests([Test | Tests], Fail, St0) ->
    {Code, Ref, St1} = expr(Test, St0),
    {Rest, St2} = guard_tests(Tests, Fail, St1),
    {[Code, check(["alku_is_true(", Ref, ")"], Fail), Rest], St2}.

check(Condition, Fail) ->
    ["if (!", Condition, ") ", Fail, "\n"].

%% ---------- Expressions ----------

body([E], St) ->
    expr(E, St);
body([E | Es], St0) ->
    {Code, _Ref, St1} = expr(E, St0),
    {Rest, Ref, St2} = body(Es, St1),
    {[Code, Rest], Ref, St2}.

expr(E, St) ->
    case literal(E) of
        {ok, Literal} -> {[], Literal, St};
        error -> compound(E, St)
    end.

compound({var, Anno, Name}, St) ->
    case St#st.vars of
        #{Name := CVar} ->
            {[], CVar, St};
        _ ->
            fail(Anno, io_lib:format("variable '~s' is bound inside a case or if "
                                      "and cannot be used after it yet", [Name]))
    end;
compound({match, _, Pattern, E}, St0) ->
    {Code, Ref, St1} = expr(E, St0),
    {Match, St2} = pattern(Pattern, Ref, ["alku_error_badmatch(", Ref, ");"], St1),
    {[Code, Match], Ref, St2};
compound({op, _, Op, A, B}, St) when Op =:= 'andalso'; Op =:= 'orelse' ->
    short_circuit(Op, A, B, St);
compound({op, Anno, Op, A, B}, St0) ->
    Fun = binary_op(Op, Anno),
    {CodeA, RefA, St1} = expr(A, St0),
    {CodeB, RefB, St2} = expr(B, St1),
    {CodeT, T, St3} = temp([Fun, "(", RefA, ", ", RefB, ")"], St2),
    {[CodeA, CodeB, CodeT], T, St3};
compound({op, Anno, Op, A}, St0) ->
    Fun = unary_op(Op, Anno),
    {CodeA, RefA, St1} = expr(A, St0),
    {CodeT, T, St2} = temp([Fun, "(", RefA, ")"], St1),
    {[CodeA, CodeT], T, St2};
compound({call, Anno, {atom, _, Name}, Args}, St) ->
    Arity = length(Args),
    case St#st.funs of
        #{{Name, Arity} := _} -> call(alku_c:function_name(Name, Arity), Args, St);
        _ -> call(builtin(erlang, Name, Arity, Anno), Args, St)
    end;
compound({call, Anno, {remote, _, {atom, _, Module}, {atom, _, Name}}, Args},
         #st{module = Module} = St) ->
    compound({call, Anno, {atom, Anno, Name}, Args}, St);
compound({call, Anno, {remote, _, {atom, _, Module}, {atom, _, Name}}, Args}, St) ->
    call(builtin(Module, Name, length(Args), Anno), Args, St);
compound({'case', _, E, Clauses}, St0) ->
    {Code, Ref, St1} = expr(E, St0),
    {Branch, Result, St2} =
        branch("case", Clauses, [Ref], ["alku_error_case_clause(", Ref, ");\n"], St1),
    {[Code, Branch], Result, St2};
compound({'if', _, Clauses}, St) ->
    branch("if", Clauses, [], "alku_error_if_clause();\n", St);
compound({block, _, Body}, St) ->
    body(Body, St);
compound(E, _St) ->
    unsupported(E).

%% case and if: every clause stores its result in one C variable and jumps
%% to the end label.
branch(Kind, Clauses, Subjects, NoMatch, St0) ->
    {Result, St1} = fresh(Kind, St0),
    {End, St2} = fresh(Kind ++ "_end", St1),
    Done = fun(Ref) -> [Result, " = ", Ref, ";\ngoto ", End, ";\n"] end,
    {Code, St3} = clauses(Clauses, Subjects, Done, NoMatch, St2),
    {["Value ", Result, ";\n", Code, End, ": ;\n"], Result, St3}.

%% andalso / orelse only evaluate B when needed.
short_circuit(Op, A, B, St0) ->
    {CodeA, RefA, St1} = expr(A, St0),
    {CodeT, T, St2} = temp(RefA, St1),
    {CodeB, RefB, St3} = expr(B, St2),
    Test = case Op of
               'andalso' -> ["alku_is_true(", T, ")"];
               'orelse' -> ["!alku_is_true(", T, ")"]
           end,
    Code = [CodeA, CodeT,
            "alku_check_boolean(", T, ");\n",
            "if (", Test, ") {\n", CodeB, T, " = ", RefB, ";\n}\n"],
    {Code, T, St3#st{vars = St2#st.vars}}.

call(CFun, Args, St0) ->
    {Codes, Refs, St1} = exprs(Args, St0),
    {CodeT, T, St2} = temp([CFun, "(", lists:join(", ", Refs), ")"], St1),
    {[Codes, CodeT], T, St2}.

exprs([], St) ->
    {[], [], St};
exprs([E | Es], St0) ->
    {Code, Ref, St1} = expr(E, St0),
    {Codes, Refs, St2} = exprs(Es, St1),
    {[Code | Codes], [Ref | Refs], St2}.

%% ---------- Literals, operators and built-ins ----------

literal({integer, Anno, N}) -> {ok, int_literal(N, Anno)};
literal({char, Anno, C}) -> {ok, int_literal(C, Anno)};
literal({op, Anno, '-', {integer, _, N}}) -> {ok, int_literal(-N, Anno)};
literal({atom, _, A}) -> {ok, ["alku_atom(", atom_literal_name(A), ")"]};
literal(_) -> error.

int_literal(N, Anno) ->
    case alku_c:fits_int64(N) of
        true ->
            ["alku_int(", alku_c:int64_literal(N), ")"];
        false ->
            fail(Anno, io_lib:format("integer ~b does not fit in 64 bits "
                                     "(big integers are not supported yet)", [N]))
    end.

atom_literal_name(Atom) ->
    alku_c:string_literal(unicode:characters_to_binary(atom_to_list(Atom))).

binary_op('+', _) -> "alku_op_add";
binary_op('-', _) -> "alku_op_sub";
binary_op('*', _) -> "alku_op_mul";
binary_op('div', _) -> "alku_op_div";
binary_op('rem', _) -> "alku_op_rem";
binary_op('==', _) -> "alku_op_eq";
binary_op('/=', _) -> "alku_op_ne";
binary_op('=:=', _) -> "alku_op_exact_eq";
binary_op('=/=', _) -> "alku_op_exact_ne";
binary_op('<', _) -> "alku_op_lt";
binary_op('>', _) -> "alku_op_gt";
binary_op('=<', _) -> "alku_op_le";
binary_op('>=', _) -> "alku_op_ge";
binary_op('and', _) -> "alku_op_and";
binary_op('or', _) -> "alku_op_or";
binary_op('xor', _) -> "alku_op_xor";
binary_op('/', Anno) ->
    fail(Anno, "the / operator needs floats, which are not supported yet; use div");
binary_op(Op, Anno) ->
    fail(Anno, io_lib:format("the ~s operator is not supported yet", [Op])).

unary_op('-', _) -> "alku_op_neg";
unary_op('+', _) -> "alku_op_plus";
unary_op('not', _) -> "alku_op_not";
unary_op(Op, Anno) ->
    fail(Anno, io_lib:format("the ~s operator is not supported yet", [Op])).

%% Built-in functions: {Module, Name, Arity} => C function in the runtime.
builtin(erlang, is_integer, 1, _) -> "alku_bif_is_integer";
builtin(erlang, is_atom, 1, _) -> "alku_bif_is_atom";
builtin(erlang, is_boolean, 1, _) -> "alku_bif_is_boolean";
builtin(erlang, abs, 1, _) -> "alku_bif_abs";
builtin(io, write, 1, _) -> "alku_io_write";
builtin(io, nl, 0, _) -> "alku_io_nl";
builtin(Module, Name, Arity, Anno) ->
    fail(Anno, io_lib:format("~s:~s/~b is not available in Alku yet",
                              [Module, Name, Arity])).

%% ---------- State and errors ----------

fresh(Prefix, #st{n = N} = St) ->
    {Prefix ++ "_" ++ integer_to_list(N), St#st{n = N + 1}}.

fresh_var(Name, #st{n = N, vars = Vars} = St) ->
    CVar = alku_c:var_name(Name, N),
    {CVar, St#st{n = N + 1, vars = Vars#{Name => CVar}}}.

temp(CExpr, St0) ->
    {T, St1} = fresh("t", St0),
    {["Value ", T, " = ", CExpr, ";\n"], T, St1}.

unsupported(E) ->
    What = case element(1, E) of
               string -> "strings are";
               cons -> "lists are";
               nil -> "lists are";
               tuple -> "tuples are";
               float -> "floats are";
               'fun' -> "funs are";
               named_fun -> "funs are";
               map -> "maps are";
               map_field_assoc -> "maps are";
               record -> "records are";
               lc -> "list comprehensions are";
               bin -> "binaries are";
               'try' -> "try expressions are";
               'catch' -> "catch expressions are";
               'receive' -> "receive expressions are (Alku has no processes)";
               _ -> "this kind of expression is"
           end,
    fail(element(2, E), [What, " not supported in Alku yet"]).

%% Anno is an erl_anno() or a plain line number.
fail(Anno, Message) ->
    throw({alku_error, erl_anno:line(Anno), Message}).
